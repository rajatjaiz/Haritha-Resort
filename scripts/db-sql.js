// Writes lib/schema.js to supabase/migrations/0001_init.sql (for the Supabase SQL editor / MCP / CLI).
const fs = require('node:fs'), path = require('node:path');
const out = path.join(__dirname, '..', 'supabase', 'migrations', '0001_init.sql');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '-- Generated by `npm run db:sql` from lib/schema.js\n' + require('../lib/schema') + '\n');
console.log('wrote', out);
